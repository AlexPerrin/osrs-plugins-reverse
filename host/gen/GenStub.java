import java.lang.reflect.*;
import java.util.*;
import java.util.stream.*;

/**
 * Emits an abstract-free Java class implementing the given interface, where every
 * abstract method throws UnsupportedOperationException. The host subclasses it and
 * overrides what it supports.
 *   java GenStub.java <interface> <package> <class>   (with the API jar on the classpath)
 */
public class GenStub {
    public static void main(String[] args) throws Exception {
        Class<?> iface = Class.forName(args[0]);
        String pkg = args[1], cls = args[2];
        StringBuilder out = new StringBuilder();
        out.append("// Generated by host/gen/GenStub.java from ").append(iface.getName()).append(". Do not edit.\n");
        out.append("package ").append(pkg).append(";\n\n");
        out.append("@SuppressWarnings({\"deprecation\", \"unchecked\", \"rawtypes\"})\n");
        out.append("public class ").append(cls).append(" implements ").append(iface.getName()).append(" {\n");
        out.append("    protected static UnsupportedOperationException unsupported(String m) {\n");
        out.append("        return new UnsupportedOperationException(\"").append(iface.getSimpleName())
           .append(".\" + m + \" is not implemented on Android yet\");\n    }\n");
        List<Method> methods = Arrays.stream(iface.getMethods())
            .filter(m -> Modifier.isAbstract(m.getModifiers()))
            .sorted(Comparator.comparing(Method::getName).thenComparing(m -> Arrays.toString(m.getParameterTypes())))
            .collect(Collectors.toList());
        Set<String> seen = new HashSet<>();
        for (Method m : methods) {
            String sig = m.getName() + Arrays.toString(m.getParameterTypes());
            if (!seen.add(sig)) continue;
            out.append("\n    @Override\n    public ");
            TypeVariable<Method>[] tvs = m.getTypeParameters();
            if (tvs.length > 0) {
                out.append("<").append(Arrays.stream(tvs).map(GenStub::typeVar).collect(Collectors.joining(", "))).append("> ");
            }
            out.append(name(m.getGenericReturnType())).append(" ").append(m.getName()).append("(");
            Type[] ps = m.getGenericParameterTypes();
            for (int i = 0; i < ps.length; i++) {
                if (i > 0) out.append(", ");
                String t = name(ps[i]);
                if (m.isVarArgs() && i == ps.length - 1) t = t.substring(0, t.length() - 2) + "...";
                out.append(t).append(" a").append(i);
            }
            out.append(") {\n        throw unsupported(\"").append(m.getName()).append("\");\n    }\n");
        }
        out.append("}\n");
        System.out.print(out);
    }

    static String typeVar(TypeVariable<?> tv) {
        Type[] b = tv.getBounds();
        if (b.length == 1 && b[0] == Object.class) return tv.getName();
        return tv.getName() + " extends " + Arrays.stream(b).map(GenStub::name).collect(Collectors.joining(" & "));
    }

    static String name(Type t) {
        return t.getTypeName().replace('$', '.');
    }
}
