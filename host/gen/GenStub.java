import java.lang.reflect.*;
import java.util.*;
import java.util.stream.*;

/**
 * Emits an abstract-free Java class implementing the given interface, where every
 * abstract method throws UnsupportedOperationException. The host subclasses it and
 * overrides what it supports.
 *   java GenStub.java <interface> <package> <class>   (with the API jar on the classpath)
 */
public class GenStub {
    public static void main(String[] args) throws Exception {
        Class<?> iface = Class.forName(args[0]);
        bind(iface);
        String pkg = args[1], cls = args[2];
        // --bag: setX/getX pairs store a value and other methods return defaults instead of throwing.
        boolean bag = args.length > 3 && args[3].equals("--bag");
        StringBuilder out = new StringBuilder();
        out.append("// Generated by host/gen/GenStub.java from ").append(iface.getName()).append(". Do not edit.\n");
        out.append("package ").append(pkg).append(";\n\n");
        out.append("@SuppressWarnings({\"deprecation\", \"unchecked\", \"rawtypes\"})\n");
        out.append("public class ").append(cls).append(" implements ").append(iface.getName()).append(" {\n");
        out.append("    protected static UnsupportedOperationException unsupported(String m) {\n");
        out.append("        return new UnsupportedOperationException(\"").append(iface.getSimpleName())
           .append(".\" + m + \" is not implemented on Android yet\");\n    }\n");
        List<Method> methods = Arrays.stream(iface.getMethods())
            .filter(m -> Modifier.isAbstract(m.getModifiers()))
            .sorted(Comparator.comparing(Method::getName).thenComparing(m -> Arrays.toString(m.getParameterTypes())))
            .collect(Collectors.toList());
        Set<String> seen = new HashSet<>();
        Map<String, String> props = new TreeMap<>();
        if (bag) {
            for (Method m : methods) {
                String p = prop(m);
                if (p != null && m.getName().startsWith("set")) props.put(p, name(m.getGenericParameterTypes()[0]));
            }
            for (Map.Entry<String, String> e : props.entrySet()) {
                out.append("    protected ").append(e.getValue()).append(" ").append(field(e.getKey())).append(";\n");
            }
        }
        for (Method m : methods) {
            String sig = m.getName() + Arrays.toString(m.getParameterTypes());
            if (!seen.add(sig)) continue;
            out.append("\n    @Override\n    public ");
            TypeVariable<Method>[] tvs = m.getTypeParameters();
            if (tvs.length > 0) {
                out.append("<").append(Arrays.stream(tvs).map(GenStub::typeVar).collect(Collectors.joining(", "))).append("> ");
            }
            out.append(name(m.getGenericReturnType())).append(" ").append(m.getName()).append("(");
            Type[] ps = m.getGenericParameterTypes();
            for (int i = 0; i < ps.length; i++) {
                if (i > 0) out.append(", ");
                String t = name(ps[i]);
                if (m.isVarArgs() && i == ps.length - 1) t = t.substring(0, t.length() - 2) + "...";
                out.append(t).append(" a").append(i);
            }
            out.append(") {\n");
            String p = bag ? prop(m) : null;
            if (p != null && props.containsKey(p) && m.getName().startsWith("set")) {
                out.append("        ").append(field(p)).append(" = a0;\n");
                if (m.getReturnType() != void.class) out.append("        return this;\n");
            } else if (p != null && props.containsKey(p) && name(m.getGenericReturnType()).equals(props.get(p))) {
                out.append("        return ").append(field(p)).append(";\n");
            } else if (bag) {
                if (m.getReturnType() != void.class) {
                    out.append("        return ").append(m.getReturnType().isAssignableFrom(iface) ? "this" : dflt(m.getReturnType())).append(";\n");
                }
            } else {
                out.append("        throw unsupported(\"").append(m.getName()).append("\");\n");
            }
            out.append("    }\n");
        }
        out.append("}\n");
        System.out.print(out);
    }

    static String prop(Method m) {
        String n = m.getName();
        if (n.startsWith("set") && m.getParameterCount() == 1) return n.substring(3);
        if (n.startsWith("get") && m.getParameterCount() == 0 && m.getReturnType() != void.class) return n.substring(3);
        if (n.startsWith("is") && m.getParameterCount() == 0 && m.getReturnType() == boolean.class) return n.substring(2);
        return null;
    }

    static String field(String prop) { return "_" + Character.toLowerCase(prop.charAt(0)) + prop.substring(1); }

    static String dflt(Class<?> t) {
        if (t == boolean.class) return "false";
        if (t == char.class) return "(char) 0";
        if (t.isPrimitive()) return "(" + t.getName() + ") 0";
        if (t == String.class) return "\"\"";
        if (t.isArray()) {
            Class<?> base = t;
            int dims = 0;
            while (base.isArray()) { base = base.getComponentType(); dims++; }
            return "new " + base.getTypeName().replace('$', '.') + "[0]" + "[]".repeat(dims - 1);
        }
        return "null";
    }

    static String typeVar(TypeVariable<?> tv) {
        Type[] b = tv.getBounds();
        if (b.length == 1 && b[0] == Object.class) return tv.getName();
        return tv.getName() + " extends " + Arrays.stream(b).map(GenStub::name).collect(Collectors.joining(" & "));
    }

    /** Type variables of generic superinterfaces (Mesh<T> in ModelData) bound to their arguments. */
    static final Map<TypeVariable<?>, Type> bound = new HashMap<>();

    static void bind(Class<?> c) {
        for (Type g : c.getGenericInterfaces()) {
            if (g instanceof ParameterizedType) {
                ParameterizedType pt = (ParameterizedType) g;
                TypeVariable<?>[] vars = ((Class<?>) pt.getRawType()).getTypeParameters();
                Type[] argsT = pt.getActualTypeArguments();
                for (int i = 0; i < vars.length; i++) bound.put(vars[i], argsT[i]);
                bind((Class<?>) pt.getRawType());
            } else if (g instanceof Class) {
                bind((Class<?>) g);
            }
        }
    }

    static String name(Type t) {
        if (t instanceof TypeVariable && bound.containsKey(t)) return name(bound.get(t));
        return t.getTypeName().replace('$', '.');
    }
}
